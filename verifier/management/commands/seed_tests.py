class Command(BaseCommand):
    help = "Створює 3 демонстраційні тести по 5 питань"

    def add_arguments(self, parser):
        parser.add_argument("--host", default="http://127.0.0.1:8000", help="адреса сервера для посилань")

    @transaction.atomic
    def handle(self, *args, **opts):
        host = opts["host"].rstrip("/")
        for data in TESTS:
            test, created = Test.objects.get_or_create(title=data["title"], defaults={"description": data["description"]})
            if created:
                for order, (text, choices, correct) in enumerate(data["questions"], start=1):
                    q = Question.objects.create(test=test, text=text, order=order)
                    Choice.objects.bulk_create(
                        Choice(question=q, text=c, is_correct=(i == correct)) for i, c in enumerate(choices)
                    )
            status = "створено" if created else "вже існує"
            self.stdout.write(f"{test.title} ({status}): {host}{reverse('test_detail', args=[test.pk])}")
